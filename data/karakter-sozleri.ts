/**
 * Belirli bir karakterin tüm sözlerini döndürür
 */
export function karakterSozleriniGetir(karakter: 'defne' | 'zeyna' | 'balim'): KarakterSozu[] {
  switch (karakter) {
    case 'defne': return defneninSozleri;
    case 'zeyna': return zeynanınSozleri;
    case 'balim': return balimınSozleri;
  }
}

/**
 * Günün karakter sözünü döndürür (tarihe göre rotate eder)
 */
export function bugunkuSozuGetir(karakter: 'defne' | 'zeyna' | 'balim'): KarakterSozu {
  const sozler = karakterSozleriniGetir(karakter);
  const gununIndeksi = Math.floor(Date.now() / (1000 * 60 * 60 * 24)) % sozler.length;
  return sozler[gununIndeksi];
}
